#!/usr/bin/env python3
"""Generate c5x_cyctab.h: base cycle count per 16-bit first instruction word, from the manual's summary tables
(doc/06a-instruction-set-summary.md, Tables 6-4..6-10; fastest-case cycles).  Most specific pattern wins; default 1."""
import re
rows=[]
for l in open('../doc/06a-instruction-set-summary.md').read().split('\n'):
    m=re.match(r"\| (\*\*)?([A-Z0-9]+)(\*\*)? \| (.*?) \| (\d+) \| ([^|]*?) \| `([01A-Za-z #]+)`( \+ 1 word)? \| ",l)
    if m: rows.append((m.group(2),int(re.match(r"\d+",m.group(6).strip()).group()),m.group(7).strip().replace(' ','')))
rows.append(('APAC',1,'1011111000000100'))
rows.append(('INTR',4,'10111110011'+format(0,'05b')[:0]+'kkkkk'))   # INTR k: 1011 1110 011k kkkk (the summary row is garbled)
tab=[1]*65536; spec=[-1]*65536
for mn,cy,p in rows:
    if len(p)!=16: continue
    mask=int(''.join('1' if c in '01' else '0' for c in p),2); val=int(''.join(c if c in '01' else '0' for c in p),2); nfix=bin(mask).count('1')
    for w in range(65536):
        if (w&mask)==val and nfix>spec[w]: tab[w]=cy; spec[w]=nfix
# manual 6.3 / Appendix B override the summary tables (07-NEW-2/3): direct B/CALL 4, delayed forms 2, MADD/MADS 2, LDP #k 2, RETCD flat 2
for lo,hi,cy in ((0x7900,0x79FF,4),(0x7A00,0x7AFF,4),(0x7D00,0x7DFF,2),(0x7E00,0x7EFF,2),(0x7F00,0x7FFF,2),(0xAA00,0xABFF,2),(0xBC00,0xBDFF,2),(0xFC00,0xFFFF,2)):
    for w in range(lo,hi+1): tab[w]=cy
with open('c5x_cyctab.h','w') as f:
    f.write("/* generated by gen_cyctab.py from the C5x manual summary tables - do not edit */\nstatic const uint8_t cyc_tab[65536] = {\n")
    for i in range(0,65536,32): f.write(' '+','.join(str(x) for x in tab[i:i+32])+',\n')
    f.write("};\n")
print("rows",len(rows),"nontrivial entries",sum(1 for x in tab if x!=1))
